import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
const js=ts.transpileModule(fs.readFileSync('lib/domain.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {localDay,overdue,validateTask}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const task={title:'Báo cáo',status:'Đang thực hiện',priority:'Cao',start:'2026-10-01',due:'2026-10-15',progress:30};
assert.equal(overdue(task,'2026-10-15'),false);
assert.equal(overdue(task,'2026-10-16'),true);
assert.equal(overdue({...task,status:'Đã hủy'},'2026-10-16'),false);
assert.equal(overdue({...task,status:'Hoàn thành'},'2026-10-16'),false);
assert.equal(overdue({...task,due:''},'2026-10-16'),false);
assert.equal(overdue({...task,archived:true},'2026-10-16'),false);
assert.equal(localDay(new Date('2026-10-15T17:00:00Z')),'2026-10-16');
assert.doesNotThrow(()=>validateTask(task));
assert.throws(()=>validateTask({...task,due:'2026-02-30'}));
assert.throws(()=>validateTask({...task,start:'2026-10-20'}));
assert.throws(()=>validateTask({...task,progress:101}));
assert.throws(()=>validateTask({...task,status:'Hoàn thành',result:''}));
assert.throws(()=>validateTask({...task,status:'Đã hủy'}));
assert.throws(()=>validateTask({...task,status:'Chờ duyệt'}));
assert.doesNotThrow(()=>validateTask({...task,status:'Hoàn thành',result:'Đã nộp báo cáo'}));
console.log('15 domain checks passed: local dates, overdue exclusions, chronology, progress and required outcomes.');
